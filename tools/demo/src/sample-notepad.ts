    '  function load() {',
    '    const text = storage.getItem(KEY);',
    '    if (text === null) return [];',
    '    try {',
    '      const parsed = JSON.parse(text);',
    '      return Array.isArray(parsed) ? parsed : [];',
    '    } catch {',
